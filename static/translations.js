// Guardar idioma activo en localStorage o detectar por defecto navegador
window.currentLang = localStorage.getItem('ag_panel_lang') || 'es';

/**
 * Función global para obtener una cadena traducida desde cualquier parte de la UI o JS
 */
window.t = function(key, fallback = '') {
    const lang = window.currentLang || 'es';
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
        return TRANSLATIONS[lang][key];
    }
    if (TRANSLATIONS['es'] && TRANSLATIONS['es'][key] !== undefined) {
        return TRANSLATIONS['es'][key];
    }
    return fallback || key;
};

/**
 * Alternar el menú desplegable de idiomas de la barra superior
 */
window.toggleLangMenu = function(e) {
    if (e) {
        e.preventDefault();
        e.stopPropagation();
    }
    const menu = document.getElementById('lang-menu-dropdown');
    if (!menu) return;
    const isVisible = (menu.style.display === 'block');
    menu.style.display = isVisible ? 'none' : 'block';
};

/**
 * Establecer un idioma concreto ('es' o 'en')
 */
window.setLanguage = function(lang, e) {
    if (e) {
        e.preventDefault();
        e.stopPropagation();
    }
    if (lang !== 'es' && lang !== 'en') lang = 'es';
    window.currentLang = lang;
    localStorage.setItem('ag_panel_lang', lang);

    const menu = document.getElementById('lang-menu-dropdown');
    if (menu) menu.style.display = 'none';

    window.applyTranslations(lang);

    if (typeof showMessage === 'function') {
        const toastMsg = (lang === 'en') 
            ? 'Language switched to English.' 
            : 'Idioma cambiado a Español.';
        showMessage(toastMsg);
    }
};

/**
 * Recorrer el DOM y traducir todos los elementos data-i18n, placeholders y títulos
 */
window.applyTranslations = function(lang) {
    if (!lang) lang = window.currentLang || localStorage.getItem('ag_panel_lang') || 'es';
    window.currentLang = lang;
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['es'];

    // 1. Textos directos
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            const badge = el.querySelector('.badge, .tab-badge, .pill-count');
            if (badge) {
                const badgeHtml = badge.outerHTML;
                el.innerHTML = dict[key] + ' ' + badgeHtml;
            } else {
                el.innerHTML = dict[key];
            }
        }
    });

    // 2. Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });

    // 3. Títulos / Tooltips
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key] !== undefined) {
            el.title = dict[key];
        }
    });

    // 4. Etiqueta del botón de idioma superior
    const label = document.getElementById('current-lang-label');
    if (label) {
        label.textContent = (lang === 'en') ? '🇬🇧 EN' : '🇪🇸 ES';
    }

    // 5. Re-renderizar vistas dinámicas activas para que adopten el nuevo idioma
    try {
        if (typeof renderTable === 'function') renderTable();
        if (typeof renderServicesCards === 'function') renderServicesCards();
        if (typeof renderLocalhostServices === 'function') renderLocalhostServices();
        if (typeof renderStaticOrderList === 'function') renderStaticOrderList();
        if (typeof renderColumnManager === 'function') renderColumnManager();
        if (typeof syncTopoControlsUI === 'function') syncTopoControlsUI();
        if (typeof updateTopoLegendUI === 'function') updateTopoLegendUI();
    } catch(err) {
        console.warn('Error refrescando UI en applyTranslations:', err);
    }
};

// Cerrar el menú si se hace clic fuera
document.addEventListener('click', function(e) {
    const wrap = document.getElementById('lang-selector-wrapper');
    const menu = document.getElementById('lang-menu-dropdown');
    if (menu && menu.style.display === 'block') {
        if (!wrap || !wrap.contains(e.target)) {
            menu.style.display = 'none';
        }
    }
});

// Auto-inicializar cuando el DOM esté listo
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function() {
        window.applyTranslations();
    });
} else {
    window.applyTranslations();
}
